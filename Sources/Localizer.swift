import Foundation

extension String {
    /// Потокобезопасное получение локализованной строки.
    /// Если язык — "Русский", возвращает исходную строку без обращения к словарям.
    var localized: String {
        guard let currentLang = UserDefaults.standard.string(forKey: "sys_language"),
              currentLang != "Русский" && !currentLang.isEmpty else {
            return self
        }
        return Localizer.translate(self, to: currentLang)
    }
}

