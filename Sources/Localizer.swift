    /// Потокобезопасный перевод строки с синхронизацией через NSLock
    static func translate(_ text: String, to lang: String) -> String {
        guard lang != "Русский" && !text.isEmpty else {
            return text
        }
        
        lock.lock()
        defer { lock.unlock() }
        
        let dict = (lang == "Հայերեն" || lang == "Armenian") ? hyTranslations : enTranslations
        
        // 1. Точное совпадение по словарю
        if let translation = dict[text] {
            return translation
        }
        
        // 2. Безопасная обработка префиксов для динамических шаблонов
        let dynamicPrefixes = [
            "Частота кадров: ",
            "Частота кадров изменена на ",
            "Параллельные потоки: ",
            "Язык изменён на ",
            "Файл ",
            "Началась отправка ",
            "Ошибка соединения с ",
            "Синхронизация: ",
            "Инструкция по настройке FTP для ",
            "Обнаружены данные для настройки ",
            "Вход через ",
            "Проверка подключения к "
        ]
        
        for prefix in dynamicPrefixes {
            if text.hasPrefix(prefix) {
                let translatedPrefix = dict[prefix] ?? prefix
                let remainder = String(text.dropFirst(prefix.count))
                let translatedRemainder = dict[remainder] ?? remainder
                return translatedPrefix + translatedRemainder
            }
        }
        
        return text
    }
