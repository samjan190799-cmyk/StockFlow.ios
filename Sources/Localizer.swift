        if lang == "Русский" {
            return text
        }
        let dict = lang == "Հայերեն" ? hyTranslations : enTranslations
        if let translation = dict[text] {
            return translation
        }
        
        // Поиск по префиксам для динамических строк
        for (key, value) in dict {
            if text.hasPrefix(key) {
                return text.replacingOccurrences(of: key, with: value)
            }
        }
        
        return text
    }
